import { readFile, writeFile, mkdir, readdir, cp, rm, stat } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { BASE, ORIGIN, newsCategories, companyCategories, validateContent } from '../portal/lib/core.mjs';
import * as pages from '../portal/lib/pages.mjs';
import { ecobalysePage } from '../portal/lib/ecobalyse.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const out = path.join(root, 'dist');
const readJSON = async name => JSON.parse(await readFile(path.join(root, 'portal/data', name), 'utf8'));
const companies = await readJSON('companies.json');
const editorial = await readJSON('editorial.json');
validateContent({ companies, editorial });
// dist is generated only; never remove source files or an unrecognised folder.
try {
  await stat(out);
  await stat(path.join(out, '.pratohub-generated'));
  await rm(out, { recursive: true });
} catch (error) {
  if (error.code !== 'ENOENT') throw error;
  try { if ((await readdir(out)).length) throw new Error('Refusing to overwrite an unrecognised dist directory'); }
  catch (readError) { if (readError.code !== 'ENOENT') throw readError; }
}
await mkdir(out, { recursive: true });
await writeFile(path.join(out, '.pratohub-generated'), 'Generated by scripts/build.mjs\n');
await cp(path.join(root, 'site'), out, { recursive: true });
await cp(path.join(root, 'portal/assets'), path.join(out, 'assets/portal'), { recursive: true });
const routes = [];
async function emit(route, html, index = true) {
  if (routes.includes(route)) throw new Error(`Duplicate route ${route}`);
  const destination = path.join(out, route, index ? 'index.html' : '');
  await mkdir(path.dirname(destination), { recursive: true });
  await writeFile(destination, html);
  routes.push(route);
}
await emit('', pages.home(companies, editorial));
await emit('news/', pages.newsPage(editorial.articles));
for (const category of Object.keys(newsCategories)) await emit(`news/${category}/`, pages.newsPage(editorial.articles, category));
for (const article of editorial.articles) await emit(`news/${article.slug}/`, pages.articlePage(article, editorial.articles));
await emit('aziende/', pages.companiesPage(companies));
for (const category of Object.keys(companyCategories)) await emit(`aziende/${category}/`, pages.companiesPage(companies, category));
for (const company of companies) await emit(`aziende/${company.slug}/`, pages.companyPage(company, companies));
await emit('market/', pages.marketPage(editorial.marketSources));
await emit('events/', pages.eventsPage(editorial.eventSources));
for (const kind of ['', 'discussions', 'questions']) await emit(`community/${kind ? kind + '/' : ''}`, pages.communityPage(kind));
await emit('ecobalyse/', ecobalysePage());
await emit('progetto/', pages.projectPage());
await emit('privacy/', pages.privacyPage());
await emit('404.html', pages.notFoundPage(), false);
await writeFile(path.join(out, '.nojekyll'), '');
const date = [...editorial.articles.map(article => article.publishedAt), ...companies.map(company => company.checkedAt)].sort().at(-1);
await writeFile(path.join(out, 'sitemap.xml'), '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + routes.filter(route => !route.endsWith('.html')).map(route => `  <url><loc>${ORIGIN}${BASE}${route}</loc><lastmod>${date}</lastmod></url>`).join('\n') + '\n</urlset>\n');
await writeFile(path.join(out, 'robots.txt'), `User-agent: *\nAllow: ${BASE}\nSitemap: ${ORIGIN}${BASE}sitemap.xml\n`);
const contentHash = createHash('sha256').update(JSON.stringify({ companies, editorial })).digest('hex');
await writeFile(path.join(out, 'release.json'), JSON.stringify({ product: 'PratoHub', version: '1.0.0', base: BASE, contentHash, routes }, null, 2) + '\n');
console.log(`BUILD PASS: ${routes.length} new routes, ${editorial.articles.length} articles, ${companies.length} companies. Previous locale routes preserved.`);
